def _build_strategy_blocks(
    model_id: str,
    strategy: str,
    org: str,
    model_name: str,
    peft_instance: str,
    spectrum_instance: str,
    full_instance: str,
) -> str:
    """Build the strategy selection code blocks with active/commented sections."""
    peft_recipe = f"hf_recipes/{org}/{model_name}--vanilla-peft-qlora.yaml"
    spectrum_recipe = f"hf_recipes/{org}/{model_name}--vanilla-spectrum.yaml"
    full_recipe = f"hf_recipes/{org}/{model_name}--vanilla-full.yaml"

    peft_block = f'''\
args = [
    "--config",
    "{peft_recipe}",
    # "--run-eval"  # enable for small models to run eval + tune
]
training_instance_type = "{peft_instance}"
training_instance_count = 1'''

    spectrum_block = f'''\
args = [
    "--config",
    "{spectrum_recipe}",
    # "--run-eval"  # enable for small models
]
training_instance_type = "{spectrum_instance}"
training_instance_count = 1'''

    full_block = f'''\
args = [
    "--config",
    "{full_recipe}",
    # "--run-eval"  # enable for small models
]
training_instance_type = "{full_instance}"
training_instance_count = 1'''

    def _comment(block: str) -> str:
        return "\n".join(f"# {line}" if line.strip() else "#" for line in block.splitlines())

    if strategy == "peft":
        return (
            f"# For PeFT (active)\n{peft_block}\n\n"
            f"## For Spectrum\n{_comment(spectrum_block)}\n\n"
            f"## For Full-Finetuning\n{_comment(full_block)}"
        )
    elif strategy == "spectrum":
        return (
            f"## For PeFT\n{_comment(peft_block)}\n\n"
            f"# For Spectrum (active)\n{spectrum_block}\n\n"
            f"## For Full-Finetuning\n{_comment(full_block)}"
        )
    else:
        return (
            f"## For PeFT\n{_comment(peft_block)}\n\n"
            f"## For Spectrum\n{_comment(spectrum_block)}\n\n"
            f"# For Full-Finetuning (active)\n{full_block}"
        )


