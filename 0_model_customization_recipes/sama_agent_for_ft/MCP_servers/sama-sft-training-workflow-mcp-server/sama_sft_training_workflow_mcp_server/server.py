@mcp.tool()
def generate_training_script(
    model_id: str,
    strategy: str = "peft",
    dataset_name: str = "AI-MO--NuminaMath-CoT",
    param_count: Optional[int] = None,
    output_dir: str = "../supervised_finetuning",
) -> Dict[str, Any]:
    """
    Generate a SageMaker training script for a model and recipe.

    This is STEP 4 (final step) of the SFT workflow. Call this AFTER
    generate_sft_recipe has created the recipe YAML. Creates a Python script
    following the established SAMA notebook pattern: session setup, data config,
    strategy selection, ModelTrainer launch. Includes active code for the selected
    strategy and commented-out blocks for the other two strategies.

    WORKFLOW: search/filter → get_model_details → generate_sft_recipe → generate_training_script

    Args:
        model_id: HuggingFace model identifier (e.g. 'meta-llama/Llama-3.2-3B-Instruct').
        strategy: Active fine-tuning strategy - 'peft', 'spectrum', or 'full'.
        dataset_name: Dataset name for the training data.
        param_count: Model parameter count (for instance type recommendation). None uses defaults.
        output_dir: Base directory for writing the script.

    Returns:
        Dictionary with status, script path, and recommended instance types.
    """
    try:
        strategy = strategy.lower()
        if strategy not in {"peft", "spectrum", "full"}:
            return {"status": "error", "message": f"Invalid strategy '{strategy}'. Must be 'peft', 'spectrum', or 'full'."}

        if "/" in model_id:
            org, model_name = model_id.split("/", 1)
        else:
            org, model_name = "models", model_id

        # Recommend instances for each strategy
        peft_instance = _recommend_instance(param_count, "peft")
        spectrum_instance = _recommend_instance(param_count, "spectrum")
        full_instance = _recommend_instance(param_count, "full")

        strategy_display = {"peft": "PEFT/LoRA (QLoRA)", "spectrum": "Spectrum", "full": "Full Fine-Tuning"}[strategy]

        strategy_blocks = _build_strategy_blocks(
            model_id, strategy, org, model_name,
            peft_instance, spectrum_instance, full_instance,
        )

        script_content = SCRIPT_TEMPLATE.format(
            model_id=model_id,
            strategy_display=strategy_display,
            dataset_name=dataset_name,
            strategy_blocks=strategy_blocks,
        )

        # Write script
        safe_name = model_id.replace("/", "--").replace(".", "-")
        script_filename = f"finetune--{safe_name}.py"
        script_path = Path(output_dir) / script_filename
        script_path.parent.mkdir(parents=True, exist_ok=True)
        script_path.write_text(script_content, encoding="utf-8")

        logger.info(f"Training script written to {script_path}")

        return {
            "status": "success",
            "message": f"Training script generated for {model_id} with {strategy_display} strategy.",
            "script_path": str(script_path),
            "script_filename": script_filename,
            "active_strategy": strategy,
            "instance_recommendations": {
                "peft": peft_instance,
                "spectrum": spectrum_instance,
                "full": full_instance,
            },
            "active_instance_type": {"peft": peft_instance, "spectrum": spectrum_instance, "full": full_instance}[strategy],
            "next_step": "Workflow complete. Summarize everything created: recipe YAML path, training script path, recommended instance type. The user can now run the generated script to launch the SageMaker training job.",
        }

    except Exception as e:
        logger.error(f"Failed to generate training script: {e}")
        return {"status": "error", "message": f"Script generation failed: {e}"}


@mcp.tool()
def get_instance_recommendation(
    param_count: int,
    strategy: str = "peft",
) -> Dict[str, Any]:
    """
    Get SageMaker instance type recommendations for a model and strategy.

    Args:
        param_count: Model parameter count (raw number, e.g. 3000000000 for 3B).
        strategy: Fine-tuning strategy - 'peft', 'spectrum', or 'full'.

    Returns:
        Recommended instance type and reasoning.
    """
    try:
        strategy = strategy.lower()
        if strategy not in {"peft", "spectrum", "full"}:
            return {"status": "error", "message": f"Invalid strategy '{strategy}'."}

        instance = _recommend_instance(param_count, strategy)
        billions = param_count / 1e9
        attn = _attn_for_instance(instance)

        all_strategies = {}
        for s in ("peft", "spectrum", "full"):
            inst = _recommend_instance(param_count, s)
            all_strategies[s] = {
                "instance_type": inst,
                "attn_implementation": _attn_for_instance(inst),
            }

        return {
            "status": "success",
            "param_count": param_count,
            "param_count_billions": round(billions, 1),
            "strategy": strategy,
            "recommended_instance_type": instance,
            "recommended_attn_implementation": attn,
            "all_strategies": all_strategies,
        }
    except Exception as e:
        return {"status": "error", "message": f"Recommendation failed: {e}"}


