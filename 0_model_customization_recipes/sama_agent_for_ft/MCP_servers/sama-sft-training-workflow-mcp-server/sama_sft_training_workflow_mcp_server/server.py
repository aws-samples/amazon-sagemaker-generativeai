# ---------------------------------------------------------------------------
# Instance type recommendations
# ---------------------------------------------------------------------------

def _recommend_instance(param_count: Optional[int], strategy: str) -> str:
    """Recommend a SageMaker instance type based on model size and strategy."""
    if param_count is None:
        return "ml.g5.2xlarge"

    billions = param_count / 1e9

    if strategy == "peft":
        if billions <= 3:
            return "ml.g5.xlarge"
        if billions <= 8:
            return "ml.g5.2xlarge"
        if billions <= 14:
            return "ml.g5.4xlarge"
        if billions <= 20:
            return "ml.p4de.24xlarge"
        return "ml.p5.48xlarge"
    elif strategy == "spectrum":
        if billions <= 3:
            return "ml.g5.2xlarge"
        if billions <= 8:
            return "ml.g5.4xlarge"
        if billions <= 20:
            return "ml.p4de.24xlarge"
        return "ml.p5.48xlarge"
    else:  # full
        if billions <= 3:
            return "ml.g5.4xlarge"
        if billions <= 8:
            return "ml.p4de.24xlarge"
        return "ml.p5.48xlarge"


def _attn_for_instance(instance_type: str) -> str:
    """Return the correct attention implementation for a SageMaker instance type.

    - P5, P6 (H100/H200 class) → kernels-community/vllm-flash-attn3
    - G5, G6, G6e, P4, P4d, P4de → kernels-community/flash-attn2
    - Unknown / None → eager
    """
    if not instance_type:
        return "eager"
    it = instance_type.lower()
    if any(x in it for x in ["p5.", "p5e.", "p6."]):
        return "kernels-community/vllm-flash-attn3"
    if any(x in it for x in ["g5.", "g6.", "g6e.", "p4.", "p4d.", "p4de."]):
        return "kernels-community/flash-attn2"
    return "eager"


